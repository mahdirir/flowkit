#!/usr/bin/env python3
"""External flowkit hook example.

flowkit passes the path to a flat JSON context file as the final argument.
Edit the file in place to change the context or the final output.
"""
import json
import sys

path = sys.argv[-1]
with open(path, encoding="utf-8") as handle:
    context = json.load(handle)

context["note"] = "annotated by an external Python hook"
context["rendered"] = "// generated by flowkit + python\n" + "python hook ran successfully\n"

with open(path, "w", encoding="utf-8") as handle:
    json.dump(context, handle)
